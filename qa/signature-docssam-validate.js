'use strict';

const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const script=fs.readFileSync(path.join(__dirname,'..','final-report-state.js'),'utf8');
const calls=[];
let stored='';
const sandbox={window:{GFIELD_AUTH:{async functionCall(_name,body){calls.push(body);if(body.action==='read-report')return {canEdit:true,comment:stored,commentUpdatedAt:null};stored=body.comment;return {comment:stored,updatedAt:'2026-09-27T00:00:00Z'};}}}};
vm.createContext(sandbox);
vm.runInContext(script,sandbox);
const state=sandbox.window.GFIELD_FINAL_REPORT_STATE;

(async()=>{
  await state.load('검증학생',2,'O'.repeat(30),'admin',false,false,'original');
  const blank=state.render();
  assert.match(blank,/수업에서 확인한 모습/);
  assert.match(blank,/풀이 습관/);
  assert.match(blank,/장점/);
  assert.match(blank,/보완할 점/);
  assert.match(blank,/주의 사항/);
  assert.match(blank,/추천 지도/);
  assert.match(blank,/시험 중 행동·운영/);
  assert.match(blank,/타이머 활용/);
  assert.match(blank,/시험지에서 확인한 풀이/);
  assert.match(blank,/시작을 오래 망설임/);
  assert.match(blank,/답을 결정·제출하기 어려움/);
  assert.match(blank,/건너뛴 문제 표시·복귀 훈련/);
  assert.match(blank,/후반 집중·주변 상황 점검/);
  assert.match(blank,/1·2회 공통 유형 전이 확인/);
  assert.doesNotMatch(blank,/data-docssam-field="lesson"[^>]*>[^<]+<\/textarea>/,'unverified observations must not be prefilled');
  const values={lesson:'교사가 확인한 <수업 기록>',examStrategy:'9번에서 표시 없이 넘어갔다.',timerUse:'타이머는 참고 신호',paperEvidence:'시험지에서 확인한 <풀이>만 기록'};
  const saved={innerHTML:'',hidden:true};
  const status={textContent:''};
  const button={disabled:false};
  const container={querySelector(selector){if(selector==='#docssam-comment-save')return button;if(selector==='#docssam-comment')return null;if(selector==='#docssam-comment-status')return status;if(selector==='.docssam-saved-comment')return saved;const match=selector.match(/data-docssam-field="([^"]+)/);return match?{value:values[match[1]]||''}:null;}};
  state.wire(container);
  await button.onclick();
  assert.equal(calls[1].exam,'original2');
  assert.equal(JSON.parse(calls[1].comment).fields.lesson,values.lesson);
  assert.equal(JSON.parse(calls[1].comment).fields.paperEvidence,values.paperEvidence);
  assert.equal(JSON.parse(calls[1].comment).fields.timerUse,values.timerUse);
  assert.match(saved.innerHTML,/&lt;수업 기록&gt;/,'saved text must be HTML escaped');
  assert.match(saved.innerHTML,/&lt;풀이&gt;/,'paper evidence must be HTML escaped');
  assert.doesNotMatch(saved.innerHTML,/<수업 기록>/);
  assert.equal(status.textContent,'저장했습니다.');
  assert.match(state.summary(),/시험 중 행동·운영[\s\S]*9번에서 표시 없이 넘어갔다/,'observed exam behavior appears on the summary sheet');
  assert.doesNotMatch(state.summary(),/타이머 활용|타이머는 참고 신호/,'timer-only advice does not displace paper evidence below scores');
  assert.doesNotMatch(state.summary(),/<수업 기록>/);
  await state.load('검증학생',1,'O'.repeat(30),'admin',false,false,'original');
  assert.equal(calls[2].exam,'original1','comment reads are round-specific');
  stored=JSON.stringify({schema:'signature-teacher-comment-v1',fields:{examStrategy:'타이머는 참고 신호'}});
  await state.load('검증학생',1,'O'.repeat(30),'admin',false,false,'original');
  assert.match(state.render(),/data-docssam-field="timerUse"[^>]*>타이머는 참고 신호<\/textarea>/,'legacy timer-only comment moves to timer field in editor');
  assert.doesNotMatch(state.summary(),/시험 중 행동·운영|타이머는 참고 신호/,'legacy timer-only comment is not described as exam-operation evidence');
  await state.load('검증학생',2,'O'.repeat(30),'admin',false,false);
  assert.equal(calls[4].exam,'final2','Final report behavior stays separate');
  stored='';
  await state.load('검증학생',2,'X'.repeat(30),'admin',false,false,'original');
  assert.equal(state.summary(),'','wrong answers alone must not create a learning profile');
  const profileButton={disabled:false};
  const profileStatus={textContent:''};
  const profileSaved={innerHTML:'',hidden:true};
  const profileCheckbox={checked:true};
  const profileEvidence={value:''};
  const profileContainer={querySelector(selector){
    if(selector==='#docssam-comment-save')return profileButton;
    if(selector==='#docssam-comment')return null;
    if(selector==='#docssam-comment-status')return profileStatus;
    if(selector==='.docssam-saved-comment')return profileSaved;
    if(selector==='[data-signature-profile="calculation-check"]')return profileCheckbox;
    if(selector==='[data-signature-profile-evidence="calculation-check"]')return profileEvidence;
    return null;
  }};
  state.wire(profileContainer);
  const before=calls.length;
  await profileButton.onclick();
  assert.equal(calls.length,before,'selected profile without observed evidence must not be saved');
  assert.match(profileStatus.textContent,/관찰 상황/);
  profileEvidence.value='원문 4번: 식은 맞고 8+7을 <틀리게> 계산';
  await profileButton.onclick();
  assert.deepEqual(JSON.parse(calls.at(-1).comment).fields.profileSignals,[{id:'calculation-check',evidence:profileEvidence.value}]);
  assert.match(state.summary(),/식은 잘 쓰지만 계산 점검 필요/);
  assert.match(state.summary(),/&lt;틀리게&gt;/,'profile evidence must be escaped');
  assert.doesNotMatch(state.summary(),/<틀리게>/);
  stored=JSON.stringify({schema:'signature-teacher-comment-v1',fields:{habit:'시작을 오래 망설인 11번',profilePriority:'answer-format',profileSignals:[
    {id:'mental-only',evidence:'3번 식 없음'},{id:'calculation-check',evidence:'4번 계산 오류'},
    {id:'answer-format',evidence:'5번 단위 오류'},{id:'puzzle-strength',evidence:'14번 규칙을 잘 찾음'}]}});
  await state.load('검증학생',2,'X'.repeat(30),'admin',false,false,'original');
  assert.match(state.render(),/기존 코멘트에서 찾은 문장 · 확인 후 선택/,'teacher observation is suggested but not auto-selected');
  const summary=state.summary();
  assert.match(summary,/이번 주 우선 · 합·개수·단위/);
  assert.match(summary,/퍼즐형 풀이 강점/,'confirmed strength must remain visible when more than three profiles exist');
  assert.doesNotMatch(summary,/식은 잘 쓰지만 계산 점검 필요/,'summary keeps teacher priority and strength while detail retains all');
  const plan=state.plan();
  assert.equal(plan.priority.id,'answer-format');
  assert.deepEqual(Array.from(plan.numbers),[5,3,4,14]);
  stored='11번 풀이 시작을 오래 망설임';
  await state.load('검증학생',2,'X'.repeat(30),'admin',false,false,'original');
  assert.match(state.render(),/data-docssam-field="lesson"[^>]*>11번 풀이 시작을 오래 망설임<\/textarea>/,'legacy plain comments stay editable');
  assert.match(state.summary(),/11번 풀이 시작을 오래 망설임/,'legacy teacher comment stays visible in summary');
  console.log('PASS Signature Docssam structured evidence-only comments, learning profiles, escaped save, round isolation, timer field');
})().catch(error=>{console.error(error);process.exitCode=1;});
