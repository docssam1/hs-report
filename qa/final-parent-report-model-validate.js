'use strict';
const assert=require('node:assert/strict');
const report=require('../final-parent-report.js');
const pts={1:10,2:20,3:30,4:40};
const rows1=[{no:1,area:'수',type:'고유1'},{no:2,area:'수',type:'반복'},{no:3,area:'도형',type:'고유3'},{no:4,area:'도형',type:'반복'}];
const rows2=[{no:1,area:'수',type:'반복'},{no:2,area:'도형',type:'고유2'},{no:3,area:'수',type:'고유3'},{no:4,area:'도형',type:'반복'}];
const taxonomy=(n,item)=>({area:item.area,subarea:'검증영역',detailType:item.type,canonicalTypeId:item.type,reviewRequired:false});
const ctx={roundNum:2,score:50,pct:30,grade:'이번 판정',items:rows2,oxArr:[...'XOOX'],miss:[1,4],ratesVerified:true,rate:{1:.9,4:.8},newScore:100};
const first={n:1,score:40,oxArr:[...'OXOX']},second={n:2,score:50,oxArr:[...'XOOX']},future={n:3,score:100,oxArr:[...'OOOO']};
const opts={attempts:[first,second,future],considered:[{n:1,pct:10},{n:2,pct:30},{n:3,pct:1}],rounds:{1:{items:rows1},2:{items:rows2},3:{items:rows1}},taxonomy,points:no=>pts[no],cumulativeBands:[['상위기준',20],['다음기준',50],['노력',100]]};
const m=report.model(ctx,opts);
assert.deepEqual(m.cumulative.personalRounds,[1,2],'future first attempts excluded');
assert.deepEqual(m.cumulative.rankRounds,[1,2],'future percentiles excluded');
assert.equal(m.cumulative.scoreAverage,45,'mean of first scores');
assert.equal(m.cumulative.percentileAverage,20,'mean of round rank percentiles');
assert.equal(m.cumulative.band,'상위기준','approved cumulative band threshold');
const area=m.areas.find(a=>a.key==='수');
assert.equal(area.current.perf,75);
assert.equal(area.cumulative.perf,57.1,'40 earned / 70 available; not the mean of round percentages');
assert.equal(area.deltaPp,17.9,'current minus cumulative in percentage points');
assert.deepEqual(m.repeatedWeaknesses.map(r=>[r.id,r.rounds]),[['반복',[1,2]]],'same type counts once per distinct round');
const one=report.model({...ctx,roundNum:1,score:40,items:rows1,oxArr:first.oxArr},{...opts,attempts:[first]});
assert.deepEqual(one.repeatedWeaknesses,[],'two misses within one round are not recurrent across rounds');
const partial=report.model({...ctx,pct:null},{...opts,considered:[{n:1,pct:10},{n:2,pct:null}]});
assert.equal(partial.current.percentile,null,'missing current percentile is not zero');
assert.deepEqual(partial.cumulative.rankRounds,[1]);
assert.equal(partial.cumulative.percentileAverage,10);
assert.equal(partial.cumulative.scoreAverage,45,'missing percentile does not discard a valid score');
const empty=report.model({...ctx,pct:null},{...opts,attempts:[],considered:[]});
assert.equal(empty.cumulative.scoreAverage,null);assert.equal(empty.cumulative.percentileAverage,null);
const repeated=report.model(ctx,{...opts,attempts:[first,second,second],considered:[{n:1,pct:10},{n:2,pct:30},{n:2,pct:30}]});
assert.equal(repeated.cumulative.scoreAverage,45,'duplicate round never receives extra weight');
assert.equal(repeated.cumulative.percentileAverage,20);
const practice=report.model({...ctx,attemptNo:2,score:100,oxArr:[...'OOOO']},opts);
assert.equal(practice.isPractice,true);assert.equal(practice.current.score,100);assert.equal(practice.cumulative.scoreAverage,45,'retake view never replaces first scores');
const unreviewed=report.model(ctx,{...opts,taxonomy:(n,it)=>({...taxonomy(n,it),reviewRequired:true})});
assert.deepEqual(unreviewed.repeatedWeaknesses,[],'unreviewed type labels cannot establish repeated weaknesses');
// Recommendation target must equal only the displayed question set, even if
// the pre-existing recommendation pool has more than three questions.
const allMiss=report.model({...ctx,miss:[1,2,3,4],score:0,newScore:100},opts);
assert.equal(allMiss.priorityItems.length,3);
assert.equal(allMiss.targetScore,60,'displayed first three contribute 10+20+30 points');
console.log('PASS parent report model: weighted rates, percentile scope, missing data, first-attempt history, distinct-round types, recommendation target');
