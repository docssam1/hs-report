assert.match(h,/1단계 · 되찾을 점수부터/);assert.match(h,/2단계 · 반복 약점 보완/);assert.match(h,/3단계 · 다음 수준 도전/);
assert.match(h,/관찰된 풀이 시간이 아닙니다/);
