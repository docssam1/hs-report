'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const dataPath=path.join(root,'bank/data/final1-fixed90.json');
const auditPath=path.join(root,'qa/final1-fixed90-content-audit.json');
const data=JSON.parse(fs.readFileSync(dataPath,'utf8'));
const audit=JSON.parse(fs.readFileSync(auditPath,'utf8'));
function permutations(values){if(values.length<=1)return [values.slice()];return values.flatMap((value,index)=>permutations(values.slice(0,index).concat(values.slice(index+1))).map(rest=>[value].concat(rest)));}
const q4=data.items.filter(item=>item.sourceNo===4).sort((a,b)=>a.variantNo-b.variantNo);
assert.equal(q4.length,3);
assert.deepEqual(new Set(q4.map(item=>item.meta.factorFormat)),new Set(['2×2','3×2','3×3']));
q4.forEach(item=>{
  const split=item.meta.factorDigitCounts[0];
  const products=permutations(item.meta.digits).map(order=>Number(order.slice(0,split).join(''))*Number(order.slice(split).join('')));
  const minimum=Math.min(...products),maximum=Math.max(...products);
  assert.equal(item.meta.minimumProduct,minimum,item.id+' minimum product');
  assert.equal(item.meta.maximumProduct,maximum,item.id+' maximum product');
  assert.equal(Number(item.answer),maximum-minimum,item.id+' independently enumerated answer');
  assert.equal(item.reviewStatus,'verified',item.id+' review status');
  const row=audit.itemReviews.find(review=>review.id===item.id);
  assert.ok(row,item.id+' audit row');
  row.questionIdentityHash=item.questionIdentityHash;
  row.itemContentHash=item.itemContentHash;
  row.reviewStatus='verified';
  row.reviewNotes=item.meta.factorFormat+' 자리 수 유형입니다. 모든 숫자 카드 순열을 별도로 열거하여 최솟값 '+minimum+', 최댓값 '+maximum+', 차 '+item.answer+'을 확인했습니다.';
  row.evidenceIds=Array.from(new Set((row.evidenceIds||[]).concat('q04-factor-format-upgrade')));
});
audit.version='1.2.0';
audit.reviewedOn='2026-09-13';
audit.frozenItemSetHash=data.freezePolicy.itemContentSetHash;
audit.questionIdentitySetHash=data.freezePolicy.questionIdentitySetHash;
audit.reviewSummary={verified:data.items.filter(item=>item.reviewStatus==='verified').length,pending:data.items.filter(item=>item.reviewStatus!=='verified').length};
const lock=audit.evidence.find(row=>row.id==='question-identity-lock');
if(lock)lock.method='풀이 필드만 제외한 지문·조건·정답·문제 그림·수치 전제의 SHA-256 집합이 '+data.freezePolicy.questionIdentitySetHash+'와 일치';
const evidence={id:'q04-factor-format-upgrade',result:'PASS 3/3',method:'파이널 1회 4번을 두 자리×두 자리, 세 자리×두 자리, 세 자리×세 자리로 한 문항씩 구성하고 각 문항의 모든 카드 순열로 최솟값·최댓값·차를 독립 계산'};
const oldIndex=audit.evidence.findIndex(row=>row.id===evidence.id);
if(oldIndex>=0)audit.evidence[oldIndex]=evidence;else audit.evidence.push(evidence);
fs.writeFileSync(auditPath,JSON.stringify(audit,null,2)+'\n','utf8');
console.log('UPDATED final1 Q4 audit: 3 factor formats independently verified');
