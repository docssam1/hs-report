'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {quota, audit} = require('../tools/question-bank/audit-balanced15.cjs');
assert.deepEqual(quota({low: 5, middle: 5, high: 5}).missing, {low: 0, middle: 0, high: 0});
assert.equal(quota({low: 15}).ready, false);
assert.equal(quota({low: 15}).missingTotal, 10);
assert.equal(quota({low: 9}).retainedOutsideQuota, 4);
assert.equal(quota({low: 9}).missingTotal, 10);
assert.equal(quota({}).missingTotal, 15);
assert.equal(quota({low: 4, middle: 5, high: 6}).ready, false);
assert.equal(quota({low: 4, middle: 5, high: 6}).missingTotal, 1);
const result = audit();
assert.equal(result.sourceCount, 900);
assert.equal(result.bankCount, 20);
assert.equal(result.storedVerified, 2130);
assert.equal(result.appliedProjection.sourceCount, 270);
assert.equal(result.appliedProjection.storedVerified, 870);
assert.equal(result.appliedProjection.targetCount, 4050);
assert.equal(result.perSourceProjection.unitsWithVariants, 498);
assert.equal(result.perSourceProjection.readyByBenchmarkCounts, 18);
assert.equal(result.appliedProjection.missingByBenchmarkCounts, 3480);
assert.equal(result.scopeConfirmed, true);
assert.equal(result.scope, 'per-source-question');
assert.deepEqual(result.perSource.filter(x=>x.benchmarkQuota.ready).map(x=>x.sourceKey).sort(), ['applied|1|1','applied|1|2','applied|1|3','applied|1|4','applied|1|5','applied|1|6','applied|1|7','applied|1|8','applied|1|9','applied|1|10','applied|1|11','applied|1|12','applied|1|13','applied|1|14','applied|1|15','applied|1|16','applied|1|17','applied|1|18'].sort());
for (const file of result.files) {
  const bytes = fs.readFileSync(path.join(__dirname, '../bank/data', file.file));
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), file.sha256);
}
assert.equal(result.perSource.reduce((n, x) => n + x.storedVerified, 0), result.storedVerified);
console.log('PASS balanced15 audit: 900 sources, 20 banks, 2130 distinct variants; preserved references counted once; exactly eighteen 5/5/5 groups; excess cannot fill another level; source benchmark and authored estimates remain separate from measured rates');
