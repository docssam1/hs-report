const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const bank=require('../bank/personal-mock.js');
function dataset(code){return JSON.parse(fs.readFileSync(path.join(__dirname,'../bank/data',code+'-fixed90.json'),'utf8'));}
function attempt(code,ox='O'.repeat(30)){return {key:code,score:{ox}};}
const original1=dataset('original1'),original2=dataset('original2');
require('../bank/important-types.js');
const libraryItems=globalThis.GFIELD_IMPORTANT_TYPES.types.flatMap(type=>type.sources.flatMap(source=>dataset('final'+source.round).items.filter(item=>item.sourceNo===source.no).map(item=>({...item,importantTypeId:type.id,importantTypeTitle:type.title}))));
const library={items:libraryItems};
const dynamic={has:()=>true,generate:(typeId,serial,anchor)=>({...anchor,id:`important-${typeId}-v${serial}`,variantNo:serial,text:`${anchor.text} 새 문제 ${typeId} ${serial}`,answer:String(serial),acceptedAnswers:[String(serial)],reviewStatus:'runtime-verified',verification:{primary:{answer:serial},independent:{answer:serial},visibleEvidence:{passed:true}}})};
const one=bank.buildPool([attempt('original1')],{original1},'all','4.2');
assert.equal(one.available,24);
assert.equal(one.missing,6);
assert.equal(one.questions.length,24);
const filled=bank.buildPool([attempt('original1')],{original1},'all','4.2',30,library);
assert.equal(filled.available,30);
assert.equal(filled.attemptCount,24);
assert.equal(filled.libraryCount,6);
assert.deepEqual([...new Set(filled.questions.map(row=>row.item.id))].length,30);
assert.ok(filled.questions.filter(row=>row.origin==='library').every(row=>row.item.pointBand==='4.2'));
assert.ok(bank.renderPaper(filled,'all','4.2','테스트').includes('자료실 공개 보충'));
const fresh=bank.buildPool([attempt('original1')],{original1},'all','4.2',30,library,dynamic,1);
assert.equal(fresh.available,30);
assert.equal(fresh.generatedCount,9);
assert.equal(fresh.attemptCount+fresh.libraryCount+fresh.generatedCount,30);
assert.ok(fresh.questions.filter(row=>row.origin==='generated').every(row=>row.item.pointBand==='4.2'));
assert.ok(bank.renderPaper(fresh,'all','4.2','테스트').includes('자료실 공개 생성형'));
const another=bank.buildPool([attempt('original1')],{original1},'all','4.2',30,library,dynamic,2);
assert.equal(another.generatedCount,9);
assert.notDeepEqual(another.questions.filter(row=>row.origin==='generated').map(row=>row.item.id),fresh.questions.filter(row=>row.origin==='generated').map(row=>row.item.id));
const unsafe={has:()=>true,generate:(typeId,serial,anchor)=>({...dynamic.generate(typeId,serial,anchor),verification:{primary:{answer:serial},independent:{answer:serial+1},visibleEvidence:{passed:true}}})};
assert.equal(bank.buildPool([attempt('original1')],{original1},'all','4.2',30,library,unsafe,1).generatedCount,0);
const wrongAnswer={has:()=>true,generate:(typeId,serial,anchor)=>({...dynamic.generate(typeId,serial,anchor),acceptedAnswers:['wrong']})};
assert.equal(bank.buildPool([attempt('original1')],{original1},'all','4.2',30,library,wrongAnswer,1).generatedCount,0);
assert.equal((bank.renderPaper(one,'all','4.2','테스트').match(/data-item-id=/g)||[]).length,24);
const both=bank.buildPool([attempt('original1'),attempt('original2')],{original1,original2},'all','4.2');
assert.equal(both.missing,0);
assert.equal(both.questions.length,30);
assert.equal(new Set(both.questions.map(row=>row.item.id)).size,30);
assert.ok(both.questions.some(row=>row.code==='original1'));
assert.ok(both.questions.some(row=>row.code==='original2'));
const wrong=bank.buildPool([attempt('original1','XXXX'+'O'.repeat(26))],{original1},'wrong','all');
assert.equal(wrong.available,12);
assert.equal(wrong.missing,18);
assert.ok(wrong.questions.every(row=>row.item.sourceNo<=4));
const wrongFilled=bank.buildPool([attempt('original1','XXXX'+'O'.repeat(26))],{original1},'wrong','all',30,library);
assert.equal(wrongFilled.libraryCount,0);
assert.equal(bank.buildPool([attempt('original1','XXXX'+'O'.repeat(26))],{original1},'wrong','all',30,library,dynamic,1).generatedCount,0);
assert.equal(wrongFilled.attemptCount,12);
assert.equal(bank.buildPool([attempt('original1')],{original1},'wrong','all',30,library).available,0);
const correct=bank.buildPool([attempt('original1','XXXX'+'O'.repeat(26))],{original1},'correct','all',10);
assert.equal(correct.target,10);
assert.equal(correct.missing,0);
assert.equal(correct.questions.length,10);
assert.ok(correct.questions.every(row=>row.item.sourceNo>4));
const ten=bank.buildPool([attempt('original1')],{original1},'all','all',10);
assert.equal(ten.questions.length,10);
assert.deepEqual(['2.7','3.4','4.2'].map(point=>ten.questions.filter(row=>row.item.pointBand===point).length),[4,3,3]);
const twenty=bank.buildPool([attempt('original1')],{original1},'all','all',20);
assert.deepEqual(['2.7','3.4','4.2'].map(point=>twenty.questions.filter(row=>row.item.pointBand===point).length),[8,7,5]);
const mock=bank.buildPool([attempt('original1')],{original1},'all','all',30);
assert.deepEqual(['2.7','3.4','4.2'].map(point=>mock.questions.filter(row=>row.item.pointBand===point).length),[12,10,8]);
const limited=bank.buildPool([attempt('original1','X'+'O'.repeat(29))],{original1},'wrong','4.2',30,library);
assert.equal(limited.attemptCount,0);
assert.equal(limited.libraryCount,0);
const allFilled=bank.buildPool([attempt('original1','X'+'O'.repeat(29))],{original1},'wrong','all',30,library);
assert.equal(allFilled.questions.length,3);
assert.deepEqual(['2.7','3.4','4.2'].map(point=>allFilled.questions.filter(row=>row.item.pointBand===point).length),[3,0,0]);
const missing=bank.buildPool([attempt('last1')],{original1},'all','all');
assert.equal(missing.available,0);
assert.equal(missing.missing,30);
assert.equal(bank.isAllowed('original1','학생',{archiveProductAccess:{'mock-signature-1':['학생']}}),true);
assert.equal(bank.isAllowed('original1','학생',{archiveProductAccess:{'mock-signature-1':['다른 학생']}}),false);
assert.equal(bank.isAllowed('final7','학생',{archiveProductAccess:{'mock-final-7':[]}}),false);
const html=bank.renderPaper(both,'all','4.2','테스트');
assert.equal((html.match(/data-item-id=/g)||[]).length,30);
assert.equal((html.match(/data-answer-id=/g)||[]).length,30);
assert.ok(html.indexOf('정답과 풀이')>html.indexOf('30번'));
