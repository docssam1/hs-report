'use strict';
const assert = require('node:assert/strict');
const forecast = require('../signature-forecast.js');
global.window = {};
require('../mock-data-original.js');
require('../mock-data-final.js');
const original = window.GFIELD_MOCK_ORIGINAL;
const final = window.GFIELD_MOCK_FINAL;
const cuts = original.rounds['1'].stats.cuts;
const final1 = final.rounds['1'].stats.cuts;

assert.equal(forecast.baseScore(0), 0);
assert.equal(forecast.baseScore(30), 30);
assert.equal(forecast.baseScore(35), 33.3);
assert.equal(forecast.baseScore(40), 36);
assert.equal(forecast.baseScore(50), 45);
assert.equal(forecast.equivalentFinalScore(28.6, final1, cuts), 30);
assert.equal(forecast.equivalentFinalScore(39.4, final1, cuts), 38);
assert.equal(forecast.estimate([25], [], cuts).expected, 25);
assert.equal(forecast.estimate([50], [], cuts).expected, 45);
assert.equal(forecast.estimate([50], [{score:28.6,cuts:final1}], cuts).expected, 43.5);
assert.equal(forecast.estimate([50], Array(3).fill({score:28.6,cuts:final1}), cuts).expected, 40.5);
assert.equal(forecast.estimate([50], [{score:100,cuts:final1}], cuts).expected, 45);
const oneRound = forecast.estimate([35], [], cuts);
assert.equal(oneRound.actual, 35);
assert.equal(oneRound.expected, 33.3);
assert.equal(forecast.estimate([35,null], [], cuts).actual, 35,'미응시를 0점으로 넣지 않음');
assert.equal(forecast.estimate([35], [{score:null,cuts:final1}], cuts).finalCount, 0,'파이널 미등록을 0점으로 넣지 않음');
const twoRounds = forecast.estimate([31.3,53.1], [], cuts);
assert.equal(twoRounds.actual, 42.2);
assert.equal(twoRounds.expected, 39.4);
assert.equal(forecast.estimate([], [], cuts), null);
const levelCuts=[['경시 가능',90],['경시컷 · 심화안정권',80],['심화컷 · 실력안정권',70],['실력컷 · 일품안정권',60],['노력요함',0]];
const positionOf=score=>({rank:1000-Math.round(score*10)});
const possible=forecast.levelPlacement(81,levelCuts,positionOf);
const waiting=forecast.levelPlacement(80.9,levelCuts,positionOf);
assert.deepEqual([possible.groupRank,possible.groupSize,possible.label],[90,100,'심화 가능 예상']);
assert.deepEqual([waiting.groupRank,waiting.groupSize,waiting.label],[91,100,'심화 대기 예상']);
assert.equal(forecast.levelPlacement(90.9,levelCuts,positionOf).label,'경시 대기 예상');
assert.equal(forecast.levelPlacement(70.9,levelCuts,positionOf).label,'실력 대기 예상');
assert.equal(forecast.levelPlacement(60.9,levelCuts,positionOf).label,'일품 대기 예상');
assert.equal(forecast.levelPlacement(59.9,levelCuts,positionOf).label,'기초 보완');
console.log('시그니처 실제/예상 점수·레벨별 90:10 석차 구간 검증 통과');
