'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');

(async()=>{
  const root=path.join(__dirname,'..');
  const out=path.join(root,'.private-work','final7-qa');
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(String(error)));

  const base=process.env.GFIELD_QA_BASE||'http://127.0.0.1:8897';
  await page.goto(base+'/final.html?round=7&name=docssam&preview=1',{waitUntil:'networkidle'});
  await page.waitForSelector('.start-doc');
  assert((await page.locator('.small-cover h1').textContent()).includes('최종 실전 모의고사 7회'));
  assert((await page.locator('.examinfo').textContent()).includes('80분'));
  await page.click('#btnPaper');
  await page.waitForSelector('.paper-image-page img');
  assert.equal(await page.locator('.paper-image-page img').count(),8,'paper viewer must show all 8 original pages');
  await page.screenshot({path:path.join(out,'paper-desktop.png'),fullPage:false});

  await page.goto(base+'/final.html?round=7&name=docssam&preview=1&go=answer',{waitUntil:'networkidle'});
  await page.waitForSelector('#agrid .abtn');
  assert.equal(await page.locator('#agrid .abtn').count(),30);
  for(const n of [1,3,5,7,9])await page.click('#agrid .abtn[data-qno="'+n+'"]');
  await page.click('#btnGrade');
  await page.waitForSelector('#report-summary',{timeout:15000});
  const body=await page.locator('body').innerText();
  assert(!body.includes('최종 1~4회 성적과 누적하지 않습니다.'));
  assert(!body.includes('최종 1~4회를 기준'));
  assert(!body.includes('반영 기준'));
  assert(!body.includes('파이널 1~7회 누적'));
  assert(!body.includes('1~7회 누적'));
  assert(!body.includes('석차 백분율\n확인 필요'),'rank percentile must be calculated from the verified process benchmark');
  assert(!body.includes('예상 등급\n확인 필요'),'expected grade must be calculated from the verified process cuts');
  await page.locator('#report-summary').screenshot({path:path.join(out,'summary-benchmark.png')});
  await page.locator('#detailedAnswersSection summary').click();
  const q29Detail=page.locator('#detailedAnswersSection [data-solution-no="29"]');
  assert.equal(await q29Detail.count(),1,'Q29 reviewed detailed solution must render once');
  const q29DetailText=await q29Detail.innerText();
  assert(q29DetailText.includes('가운데가 1이면'));
  assert(q29DetailText.includes('4×3×2×1=24가지'));
  assert(q29DetailText.includes('4×2×24=192가지'));
  await q29Detail.screenshot({path:path.join(out,'q29-detailed-solution.png')});
  const q6Tutor=page.locator('#detailedAnswersSection .f7ot-card[data-solution-no="6"]');
  assert.equal(await q6Tutor.count(),1,'Q6 has one original-question tutor card');
  assert.equal(await q6Tutor.locator('.f7ot-source--problem image').getAttribute('href'),'materials/final_7/002.jpg','Q6 tutor uses the exact original page image');
  await q6Tutor.locator('.f7ot-launch').click();
  assert.equal(await page.locator('#final7OriginalTutor').isVisible(),true,'Q6 original tutor opens');
  assert.match(await page.locator('.f7ot-head').innerText(),/선생님 대본으로 배우는 원문 풀이/);
  await page.getByRole('button',{name:'6번 풀이 시작'}).click();
  assert.match(await page.locator('.f7ot-teacher').innerText(),/앞 물고기의 꼬리와 다음 물고기의 머리/,'source-script head-tail criterion appears first');
  await page.getByRole('button',{name:'모르겠어요 · 선을 이어서 보여 주세요'}).click();
  await page.locator('.f7ot-guide.is-playing').waitFor();
  assert.equal(await page.locator('.f7ot-guide.is-playing').count(),1,'not-understood path reveals the continuous-line guide');
  assert.match(await page.locator('.f7ot-teacher').innerText(),/교차해도 옆 선으로 넘어가지 않습니다/);
  await page.getByRole('button',{name:'이해되었어요 · 물고기를 셀게요'}).click();
  assert.match(await page.locator('.f7ot-answer').innerText(),/6마리/,'source-specific tutor ends at the verified answer');
  await page.locator('.f7ot-close').click();
  const q11Tutor=page.locator('#detailedAnswersSection .f7ot-card[data-solution-no="11"]');
  assert.equal(await q11Tutor.count(),1,'Q11 has one original-question tutor card');
  assert.equal(await q11Tutor.locator('.f7ot-source--q11 image').getAttribute('href'),'materials/final_7/003.jpg','Q11 tutor uses the exact original page image');
  await q11Tutor.locator('.f7ot-launch').click();
  await page.getByRole('button',{name:'11번 풀이 시작'}).click();
  assert.match(await page.locator('.f7ot-teacher').innerText(),/40개/,'Q11 separates the last chair');
  assert.match(await page.locator('.f7ot-teacher').innerText(),/122명/,'Q11 separates the three people on the last chair');
  await page.getByRole('button',{name:'이해했어요 · 첫 번째 차이 보기'}).click();
  assert.match(await page.locator('.f7ot-teacher').innerText(),/차이는 3자리/,'Q11 starts uggigi from the seat difference');
  await page.getByRole('button',{name:'기억나요 · 모두 2인용으로 우겨 볼게요'}).click();
  assert.match(await page.locator('.f7ot-math-scene').innerText(),/122 − 80 = 42명/,'Q11 verifies the remaining forty-two people');
  await page.getByRole('button',{name:'이해했어요 · 5인용 수 구하기'}).click();
  assert.match(await page.locator('.f7ot-answer').innerText(),/15개/,'Q11 ends at the verified answer');
  await page.locator('.f7ot-close').click();
  const q12Tutor=page.locator('#detailedAnswersSection .f7ot-card[data-solution-no="12"]');
  assert.equal(await q12Tutor.count(),1,'Q12 has one original-question tutor card');
  assert.equal(await q12Tutor.locator('.f7ot-source--q12 image').getAttribute('href'),'materials/final_7/003.jpg','Q12 tutor uses the exact original page image');
  await q12Tutor.locator('.f7ot-launch').click();
  await page.getByRole('button',{name:'12번 풀이 시작'}).click();
  assert.match(await page.locator('.f7ot-q12-equation').innerText(),/2\/16 = 1\/8/,'Q12 converts the source pattern to fractions');
  await page.getByRole('button',{name:'이해했어요 · 넓이 규칙 보기'}).click();
  assert.match(await page.locator('.f7ot-teacher').innerText(),/앞 단계의 1\/4/,'Q12 identifies the one-quarter recurrence');
  await page.getByRole('button',{name:'이해했어요 · 세 번째 확인하기'}).click();
  await page.getByRole('button',{name:'알겠어요 · 네 번째 구하기'}).click();
  assert.match(await page.locator('.f7ot-answer').innerText(),/1\/128/,'Q12 ends at the verified fraction');
  await page.locator('.f7ot-close').click();
  const q13Tutor=page.locator('#detailedAnswersSection .f7ot-card[data-solution-no="13"]');
  assert.equal(await q13Tutor.count(),1,'Q13 has one original-question tutor card');
  assert.equal(await q13Tutor.locator('.f7ot-source--q13 image').getAttribute('href'),'materials/final_7/004.jpg','Q13 tutor uses the exact original page image');
  await q13Tutor.locator('.f7ot-launch').click();
  await page.getByRole('button',{name:'13번 풀이 시작'}).click();
  await page.getByRole('button',{name:'이해했어요 · 300개 경계 찾기'}).click();
  assert.match(await page.locator('.f7ot-q13-boundary').innerText(),/210[\s\S]*90[\s\S]*300/,'Q13 locates the exact 300-term boundary');
  await page.getByRole('button',{name:'이해했어요 · 1과 2 비교하기'}).click();
  await page.getByRole('button',{name:'12쌍이에요 · 답 확인하기'}).click();
  assert.match(await page.locator('.f7ot-answer').innerText(),/2가 12개 더 많음/,'Q13 ends at the verified comparison');
  await page.locator('.f7ot-close').click();
  assert.equal(await page.evaluate(()=>!!window.GFIELD_FINAL_REPORT_PRINT),true,'diagnostic print helper must load for Final 7');
  await page.screenshot({path:path.join(out,'report-desktop.png'),fullPage:false});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(100);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
  assert(overflow<=1,'390px report must not overflow horizontally: '+overflow+'px');
  await page.screenshot({path:path.join(out,'report-mobile.png'),fullPage:false});
  await page.setViewportSize({width:1440,height:1000});

  await page.goto(base+'/answer.html?set=final&round=7&name=docssam',{waitUntil:'networkidle'});
  await page.waitForSelector('#body tr');
  assert.equal(await page.locator('#body tr').count(),30,'answer table must show 30 source answers');
  assert.equal((await page.locator('#body tr').nth(18).locator('.ans').innerText()).trim(),'382개');
  assert.equal((await page.locator('#body tr').nth(9).locator('.ans').innerText()).trim(),'50');
  const q29Row=page.locator('#body tr').nth(28);
  assert.equal((await q29Row.locator('.ans').innerText()).trim(),'192가지');
  const q29Text=await q29Row.innerText();
  assert(q29Text.includes('✓ 필기 해설 정정:'));
  assert(q29Text.includes('공식 답안과 영상의 64가지'));
  assert.equal(await page.getByText('교재 목차 대조 전',{exact:true}).count(),30,'unreviewed textbook links must not be guessed');
  await page.screenshot({path:path.join(out,'answer-desktop.png'),fullPage:false});

  assert.deepEqual(errors,[],'browser page errors: '+errors.join(' | '));
  await browser.close();
  console.log('PASS Final 7 desktop paper, 30-answer table, and standalone report visual smoke test');
})().catch(error=>{console.error(error);process.exit(1);});
